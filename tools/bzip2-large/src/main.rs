//! Manual streaming validation; artifacts must stay outside the repository.
use bzip2_turbo::{
    Action, Compress, Compression, Decoder, Decompress, Encoder, EncoderOptions, Status,
};
use std::{
    fs::File,
    io::{self, BufReader, BufWriter, Read, Write},
    sync::{
        Arc,
        atomic::{AtomicU64, Ordering},
    },
};
const SIZE: u64 = (1u64 << 32) + 65536;
struct Fixture {
    media: bool,
    pos: u64,
    state: u64,
    header: Vec<u8>,
}
impl Fixture {
    fn new(media: bool) -> Self {
        let mut h = Vec::new();
        if media {
            h.extend(b"RF64");
            h.extend(u32::MAX.to_le_bytes());
            h.extend(b"WAVEds64");
            h.extend(28u32.to_le_bytes());
            h.extend((SIZE - 8).to_le_bytes());
            h.extend((SIZE - 80).to_le_bytes());
            h.extend(((SIZE - 80) / 4).to_le_bytes());
            h.extend(0u32.to_le_bytes());
            h.extend(b"fmt ");
            h.extend(16u32.to_le_bytes());
            h.extend(1u16.to_le_bytes());
            h.extend(2u16.to_le_bytes());
            h.extend(48000u32.to_le_bytes());
            h.extend(192000u32.to_le_bytes());
            h.extend(4u16.to_le_bytes());
            h.extend(16u16.to_le_bytes());
            h.extend(b"data");
            h.extend(u32::MAX.to_le_bytes());
            assert_eq!(h.len(), 80);
        }
        Self {
            media,
            pos: 0,
            state: 0x9e3779b97f4a7c15,
            header: h,
        }
    }
}
impl Read for Fixture {
    fn read(&mut self, out: &mut [u8]) -> io::Result<usize> {
        let n = out.len().min((SIZE - self.pos) as usize);
        let text =
            b"Streaming compression validation: boundary lengths, records, and repeated text.\n";
        for b in &mut out[..n] {
            *b = if self.pos < self.header.len() as u64 {
                self.header[self.pos as usize]
            } else if self.media {
                self.state ^= self.state << 13;
                self.state ^= self.state >> 7;
                self.state ^= self.state << 17;
                (self.state >> 32) as u8
            } else {
                text[self.pos as usize % text.len()]
            };
            self.pos += 1;
        }
        Ok(n)
    }
}
fn compare(mut input: impl Read, media: bool) -> io::Result<u64> {
    let mut expected = Fixture::new(media);
    let mut a = [0; 65536];
    let mut b = [0; 65536];
    let mut total = 0;
    loop {
        let n = input.read(&mut a)?;
        if n == 0 {
            break;
        }
        expected.read_exact(&mut b[..n])?;
        if a[..n] != b[..n] {
            return Err(io::Error::other(format!("mismatch at {total}")));
        }
        total += n as u64;
    }
    if total != SIZE {
        return Err(io::Error::other(format!("length {total}, expected {SIZE}")));
    }
    Ok(total)
}
fn main() -> Result<(), Box<dyn std::error::Error>> {
    let a: Vec<_> = std::env::args().collect();
    let mode = a.get(1).ok_or("mode required")?;
    let media = match a.get(2).map(String::as_str) {
        Some("text") => false,
        Some("media") => true,
        _ => return Err("text|media required".into()),
    };
    let path = a.get(3).ok_or("path required")?;
    let threads: usize = a.get(4).map_or(Ok(1), |s| s.parse())?;
    if threads == 0 {
        return Err("threads must be positive".into());
    }
    match mode.as_str() {
        "generate" => {
            let mut o = BufWriter::new(File::create(path)?);
            let n = io::copy(&mut Fixture::new(media), &mut o)?;
            o.flush()?;
            println!("generated bytes={n}");
        }
        "verify" => {
            let n = compare(io::stdin().lock(), media)?;
            println!("verified bytes={n}");
        }
        "encode" => {
            let mut o = Encoder::new(
                BufWriter::new(File::create(path)?),
                EncoderOptions {
                    level: 1,
                    threads,
                    block_size: Some(100000),
                    passes: Some(1),
                },
            );
            let n = io::copy(&mut Fixture::new(media), &mut o)?;
            o.finish()?.flush()?;
            println!(
                "encoded input={n} output={}",
                std::fs::metadata(path)?.len()
            );
        }
        "decode" => {
            let observed = Arc::new(AtomicU64::new(0));
            let callback = observed.clone();
            let d = Decoder::with_output_callback(
                BufReader::new(File::open(path)?),
                threads,
                move |b| {
                    callback.fetch_add(b.len() as u64, Ordering::Relaxed);
                },
            );
            let n = compare(d, media)?;
            assert_eq!(observed.load(Ordering::Relaxed), n);
            println!("decoded verified={n} callback={n}");
        }
        "raw-encode" => {
            let mut source = Fixture::new(media);
            let mut codec = Compress::new(Compression::new(1), 30);
            let mut output = BufWriter::new(File::create(path)?);
            let mut input = [0; 65536];
            let mut dest = [0; 8191];
            loop {
                let n = source.read(&mut input)?;
                let mut used = 0;
                let action = if n == 0 { Action::Finish } else { Action::Run };
                loop {
                    let before = codec.total_in();
                    let written = codec.total_out();
                    let status = codec.compress(&input[used..n], &mut dest, action)?;
                    used += (codec.total_in() - before) as usize;
                    let got = (codec.total_out() - written) as usize;
                    output.write_all(&dest[..got])?;
                    if status == Status::StreamEnd {
                        assert_eq!(codec.total_in(), SIZE);
                        output.flush()?;
                        println!(
                            "raw encoded input={} output={}",
                            codec.total_in(),
                            codec.total_out()
                        );
                        return Ok(());
                    }
                    if used == n && n != 0 {
                        break;
                    }
                    if codec.total_in() == before && got == 0 {
                        return Err("raw encoder stalled".into());
                    }
                }
            }
        }
        "raw-decode" => {
            let mut input = BufReader::new(File::open(path)?);
            let mut codec = Decompress::new(false);
            let mut source = [0; 8191];
            let mut dest = [0; 65536];
            let mut expected = Fixture::new(media);
            let mut reference = [0; 65536];
            loop {
                let n = input.read(&mut source)?;
                let mut used = 0;
                loop {
                    let before = codec.total_in();
                    let written = codec.total_out();
                    let status = codec.decompress(&source[used..n], &mut dest)?;
                    used += (codec.total_in() - before) as usize;
                    let got = (codec.total_out() - written) as usize;
                    expected.read_exact(&mut reference[..got])?;
                    assert_eq!(dest[..got], reference[..got]);
                    if status == Status::StreamEnd {
                        assert_eq!(codec.total_out(), SIZE);
                        assert_eq!(codec.total_in(), std::fs::metadata(path)?.len());
                        println!(
                            "raw decoded input={} output={}",
                            codec.total_in(),
                            codec.total_out()
                        );
                        return Ok(());
                    }
                    if used == n && n != 0 {
                        break;
                    }
                    if codec.total_in() == before && got == 0 {
                        return Err("raw decoder stalled or truncated".into());
                    }
                }
            }
        }
        _ => return Err("unknown mode".into()),
    }
    Ok(())
}
